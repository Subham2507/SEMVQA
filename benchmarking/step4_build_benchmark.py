import argparse
import csv
import json
import os
import shutil
from collections import Counter

VQA = "."

PROMPT_EVIDENCE = (
    "You are looking at a scanning electron microscopy (SEM) image.\n"
    "Question: {QUESTION}\n"
    "Respond in exactly this format:\n"
    "Evidence: <the specific visible evidence that supports your answer>\n"
    "Answer: <your answer for question for given image>"
)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--subset-json",
                     default=f"{VQA}/training_data/dinov3_clusters_kmeans/representative_subset_300.json")

    ap.add_argument("--source-jsonl", default=f"{VQA}/sem_vqa_corpus.jsonl")

    ap.add_argument("--unique-csv", default=None)
    ap.add_argument("--image-dir", default=f"{VQA}/images_full/images_full")
    ap.add_argument("--output-dir", default=f"{VQA}/benchmark_rep300")
    args = ap.parse_args()

    subset = json.load(open(args.subset_json))
    meta_by_image = {r["filename"]: r for r in subset}
    print(f"{len(subset)} representative images")

    ncopies_of = {}
    if args.unique_csv:
        for r in csv.DictReader(open(args.unique_csv)):
            for a in r["aliases"].split(";"):
                ncopies_of[a] = int(r["n_copies"])

    img_out = os.path.join(args.output_dir, "images")
    os.makedirs(img_out, exist_ok=True)

    records, missing_img = [], []
    for line in open(args.source_jsonl):
        r = json.loads(line)
        fn = r["filename"]
        if fn not in meta_by_image:
            continue
        m = meta_by_image[fn]
        question = r["question"].strip()
        records.append({
            "id": f"{fn}_{r['q_index']}",
            "image": f"images/{fn}",
            "filename": fn,
            "md5": r.get("md5", ""),
            "n_copies_in_dataset": ncopies_of.get(fn, 1),

            "corpus_split": r.get("split", "unknown"),
            "question": question,
            "reference_answer": r["answer"].strip(),
            "reference_evidence": (r.get("visual_evidence") or "").strip(),
            "level": (r.get("level") or "").strip().lower(),
            "feature": (r.get("feature") or "").strip(),
            "cluster_id": m["cluster_id"],
            "centrality": m["centrality"],
            "distance_to_centroid": m["distance_to_centroid"],
            "prompt_plain": question,
            "prompt_evidence": PROMPT_EVIDENCE.format(QUESTION=question),
        })

    records.sort(key=lambda r: r["id"])
    print(f"{len(records)} QA records assembled")

    copied = 0
    for fn in sorted(meta_by_image):
        src, dst = os.path.join(args.image_dir, fn), os.path.join(img_out, fn)
        if not os.path.exists(src):
            missing_img.append(fn); continue
        if not os.path.exists(dst):
            shutil.copy2(src, dst)
        copied += 1
    print(f"{copied}/{len(meta_by_image)} images present in {img_out}")
    if missing_img:
        print(f"  [WARNING] missing on disk: {missing_img[:5]}")

    imgs_with_qa = {r["filename"] for r in records}
    no_qa = sorted(set(meta_by_image) - imgs_with_qa)
    if no_qa:
        print(f"  [WARNING] {len(no_qa)} representative images have NO QA in the source: {no_qa[:5]}")

    out_json = os.path.join(args.output_dir, "benchmark_rep300.json")
    json.dump(records, open(out_json, "w"), indent=1)
    print(f"\nWrote {out_json}")

    lv = Counter(r["level"] for r in records)
    sp = Counter(r["corpus_split"] for r in records)
    ce = Counter(r["centrality"] for r in records)
    cl = Counter(r["cluster_id"] for r in records)
    per_img = Counter(r["filename"] for r in records)
    dup = sum(1 for r in records if r["n_copies_in_dataset"] > 1)
    n_md5 = len({r["md5"] for r in records if r["md5"]})
    print(f"  unique images        : {len(per_img)}")
    print(f"  distinct md5s        : {n_md5}  (should equal unique images if all distinct)")
    print(f"  QA per image         : min={min(per_img.values())} max={max(per_img.values())} "
          f"mean={len(records)/len(per_img):.2f}")
    print(f"  by corpus_split      : {dict(sp)}")
    print(f"  by level             : {dict(lv)}")
    print(f"  by centrality        : {dict(ce)}")
    print(f"  by cluster           : {dict(sorted(cl.items()))}")
    print(f"  records whose image has duplicates elsewhere: {dup}")

    readme = f"""# rep300 benchmark — frozen input for multi-model evaluation

Auto-generated by `step4_build_benchmark.py`. **Do not hand-edit.**

Frozen so that all model runs read byte-identical inputs: re-deriving this 3-way join
(cluster assignment x QA corpus x image files) separately for every evaluation run is a
silent-input-corruption risk that is cheaper to eliminate by freezing the join once.

## Contents
- `images/` — {copied} canonical images (copied from `images_full/images_full/`)
- `benchmark_rep300.json` — {len(records)} QA records over {len(per_img)} images

## Provenance
Images come from `training_data/dinov3_clusters_kmeans/representative_subset_300.json`
(the rep300 representative set: 5 DINOv3 clusters × 3 centrality bands × 20 images, selected to
maximise question-level and feature coverage). QA text comes from `sem_vqa_corpus.jsonl`.

## Schema
| Field | Meaning |
|---|---|
| `id` | `<filename>_<q_index>`, unique |
| `image` | path relative to this folder |
| `filename`, `md5`, `n_copies_in_dataset` | image identity; `md5` makes the set auditable against the corpus's duplicate-image records |
| `corpus_split` | the split this image holds in `sem_vqa_corpus.jsonl` (`benchmark` for all 300) |
| `question` | question text |
| `reference_answer`, `reference_evidence` | gold answer and gold visual evidence |
| `level`, `feature` | question level (lowercased) and feature label |
| `cluster_id`, `centrality`, `distance_to_centroid` | DINOv3 selection metadata |
| `prompt_plain` | the question as-is |
| `prompt_evidence` | structured SEM template requesting `Evidence:` / `Answer:` |

## ⚠️ Split caveat
{sp.get('train', 0)} of these records are on images in **this project's training split**
({sp.get('test', 0)} in test). That is irrelevant for any model that never trained on this
corpus, but a model fine-tuned by this project on the corpus's train split will have seen the
train-split images during training. Any comparison between such models must either restrict
to `split == "test"` or disclose the difference.

Also note {dup} records sit on images that have byte-identical duplicates elsewhere in the
dataset. The 300 images themselves are verified distinct from one another.

## Distributions
- split: {dict(sp)}
- level: {dict(lv)}
- centrality: {dict(ce)}
- cluster: {dict(sorted(cl.items()))}
"""
    open(os.path.join(args.output_dir, "README.md"), "w").write(readme)
    print(f"Wrote {os.path.join(args.output_dir, 'README.md')}")

if __name__ == "__main__":
    main()
